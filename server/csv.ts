/**
 * Общее для выгрузок в CSV. Excel на русской локали ждёт «;» разделителем,
 * запятую в дробной части и BOM в начале файла — иначе кириллица приезжает
 * кракозябрами, а числа становятся текстом.
 */

/** Тиыны → «1234,56». Единственное место, где сервер делит на 100. */
export function csvMoney(minor: number): string {
  return (minor / 100).toFixed(2).replace('.', ',');
}

/**
 * Ячейка, с которой Excel начнёт считать формулу: «=», «+», «-», «@», а также
 * табуляция и возврат каретки — их Excel отбрасывает и смотрит на следующий
 * символ. В выгрузку идут пользовательские поля (назначение платежа, номер
 * документа, имя контрагента), и открывают её именно в Excel — значит чужой
 * текст стал бы исполняемым: `=HYPERLINK(...)` уводит данные наружу одним
 * кликом бухгалтера.
 */
const FORMULA_START = /^[=+\-@\t\r]/;

/**
 * Чистое число (в том числе отрицательное сальдо из csvMoney) формулой быть
 * не может. Без этой поблажки апостроф встал бы перед каждым «-3400,00», и
 * все минусовые суммы приехали бы в отчёт текстом, который Excel не считает.
 */
const PLAIN_NUMBER = /^-?\d+(?:,\d+)?$/;

/** Экранирование ячейки: формулы, кавычки, «;» и переводы строк. */
export function csvCell(value: unknown): string {
  const raw = value === null || value === undefined ? '' : String(value);
  // Апостроф в начале — штатный для Excel способ сказать «это текст»; сам он
  // в ячейке не показывается.
  const s = FORMULA_START.test(raw) && !PLAIN_NUMBER.test(raw) ? `'${raw}` : raw;
  // Одинокий \r без кавычек разорвал бы строку не хуже \n: строки склеиваются
  // через CRLF, и Excel принял бы его за начало новой записи.
  return /[";\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function csvRow(cells: unknown[]): string {
  return cells.map(csvCell).join(';');
}

/** Готовое тело файла: BOM для Excel и CRLF между строками. */
export function csvBody(rows: string[]): string {
  return '﻿' + rows.join('\r\n');
}
